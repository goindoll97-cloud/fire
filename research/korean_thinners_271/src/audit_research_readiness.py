# -*- coding: utf-8 -*-
"""Research-ready coverage, version-control and property-evidence gate for MSDS records.

No molecular/property/OEL approvals are inferred from molecule names or the pilot 7 CAS.
Input: CSVs generated by build_msds_registry.py. Uses Python standard library only.
"""
from __future__ import annotations
import argparse
import collections
import csv
import json
from pathlib import Path

PILOT_CAS={'71-43-2','67-64-1','141-78-6','108-88-3','67-56-1','123-86-4','108-10-1'}

def read(path):
    with Path(path).open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
def write(path, rows, cols):
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('w',encoding='utf-8-sig',newline='') as f:
        w=csv.DictWriter(f,fieldnames=cols,extrasaction='ignore');w.writeheader();w.writerows(rows)
def v(x):return str(x).strip()=='예'

def create_report(source, out):
    source=Path(source);out=Path(out);out.mkdir(parents=True,exist_ok=True)
    docs=read(source/'문서원본.csv');comps=read(source/'성분근거.csv');master=read(source/'CAS기본마스터.csv')
    bydoc=collections.defaultdict(list)
    for c in comps:bydoc[c['문서키']].append(c)
    coverage=[];use_count=collections.Counter();priority=collections.Counter();unlocks=collections.Counter();
    mix_docs=0;ready_candidates=0;current6=0;unresolved=[]
    for d in docs:
        entries=bydoc[d['문서키']]
        cas={c['CAS'] for c in entries}
        mixtures={c['CAS'] for c in entries if c['CAS분류']=='복합물/이성질체혼합물'}
        complete=v(d['함량합계100가능_표기성분만']) and len(cas)>=2
        missing=cas-PILOT_CAS
        structural=complete and not mixtures and all(c['CAS검증']=='형식유효' for c in entries)
        if mixtures:mix_docs+=1
        if structural:
            ready_candidates+=1
            for c in missing:priority[c]+=1
            if len(missing)==1:unlocks[next(iter(missing))]+=1
            if not missing:current6+=1
        use_count[d['용도태그_잠정']]+=1
        flags=[]
        if len(cas)<2:flags.append('단일성분 또는 CAS 추출 누락')
        if not v(d['함량합계100가능_표기성분만']):flags.append('함량합계100 불가 또는 수동검토')
        if mixtures:flags.append('복합성분·혼합이성질체 포함')
        if missing:flags.append('파일럿물성7종 밖 CAS: '+', '.join(sorted(missing)))
        if not flags:flags=['파일럿 물성 후보만 존재·출처 미검증']
        coverage.append({
           '문서키':d['문서키'],'기존제품ID':d['기존제품ID'],'제조사':d['제조사'],
           '제품명':d['제품명_파일명기반'],'잠정용도':d['용도태그_잠정'],
           '구성성분수':len(cas),'기재함량합계100가능':d['함량합계100가능_표기성분만'],
           '혼합물·UVCB유무':'예' if mixtures else '아니오',
           '파일럿7종만으로_수치시험후보':'예' if structural and not missing else '아니오',
           '순물질만_원문검증대기후보':'예' if structural else '아니오',
           '추가필요CAS': '|'.join(sorted(missing)),
           '모델적용판정':'미승인_구조및물성출처수동검증필수',
           '제외/보류사유':' ; '.join(flags),
        })
    cas_prio=[]
    for r in master:
        cas=r['CAS'];u=unlocks[cas]
        cas_prio.append({
            'CAS':cas,'PDF문서포함수':int(r['포함PDF수']),
            '현재7종외순물질후보내_출현수':priority[cas],
            '이CAS하나만보완시_추가수치시험후보':u,
            '혼합물·이성질체':'예' if r['복합물또는이성질체'] else '아니오',
            '참고순물성보유상태':'파일럿_미검증' if cas in PILOT_CAS else '없음',
            'SMILES':'', '분자량_g_mol':'', '25C_포화증기압_kPa':'',
            '온도_K':'298.15', '구조공식출처':'','물성출처와측정조건':'',
            '실측또는DB근거문헌':'', '구조검증상태':'미검증','물성검증상태':'미검증',
            '한글국내TWA_ppm':'', '한국TWA공식출처':'','한국TWA검증상태':'미검증',
            'HANNA입력승인':'미승인',
        })
    cas_prio.sort(key=lambda r:(-r['이CAS하나만보완시_추가수치시험후보'],-r['현재7종외순물질후보내_출현수'],-r['PDF문서포함수'],r['CAS']))
    docs_by_name=collections.defaultdict(list)
    for d in docs:
        norm=''.join(str(d['제품명_파일명기반']).lower().split())
        docs_by_name[(d['제조사'],norm)].append(d)
    version=[]
    for (brand,_),dlist in docs_by_name.items():
        if len(dlist)<2:continue
        for d in dlist:
            version.append({'제조사':brand,'명칭기준_제품명':d['제품명_파일명기반'],
                '동명PDF수':len(dlist),'문서키':d['문서키'],'기존제품ID':d['기존제품ID'],
                '원본파일명':d['원본PDF파일명'],'원본SHA256':d['원본SHA256'],
                'MSDS번호_잠정':d['원문MSDS번호_잠정'],
                '개정판/다른제품판정':'미검증','수동판정근거':'',
            })
    priority_cols=list(cas_prio[0]);coverage_cols=list(coverage[0]);
    write(out/'MSDS_270_모델적용성_평가.csv',coverage,coverage_cols)
    write(out/'CAS_54종_물성보완_우선순위및승인서식.csv',cas_prio,priority_cols)
    write(out/'동명제품_중복개정_검토.csv',version,list(version[0]) if version else ['제조사','문서키'])
    use_rows=[{'용도분류_잠정':k,'PDF수':v,'판정':'원문MSDS제1항·TDS 검토전'} for k,v in use_count.most_common()]
    write(out/'용도분류_잠정집계.csv',use_rows,list(use_rows[0]))
    summary={
        'source_docs':len(docs),'source_component_records':len(comps),'distinct_cas':len(master),
        'documents_with_named_mixture_uvcb':mix_docs,
        'only_pure_candidates_and_feasible_intervals':ready_candidates,
        'pilot7_numeric_scenario_candidates_unverified':current6,
        'name_duplicate_review_rows':len(version),
        'source_composition_constraints':'MSDS interval only; missing disclosed composition possible',
        'future_unlock_single_CAS':[{'CAS':k,'potential_additional_documents':v} for k,v in unlocks.most_common()],
        'not_done':['Independent chemistry property verification','Current Korean OEL verification',
          'VLE measurement validation','Use/compatibility verification','Physically feasible optimized blend validation'],
        'risk_note':'No safety ranking, measured emission, exposure estimate or approved substitution claim',
    }
    (out/'DB_연구진행_진단.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(summary,ensure_ascii=False,indent=2))
    return summary

def approved_property_records(path):
    records=read(path)
    for x in records:
        if x.get('HANNA입력승인')!='승인':continue
        if x.get('혼합물·이성질체')=='예':raise ValueError(f"혼합물/CAS를 단일 SMILES로 승인 금지: {x['CAS']}")
        for tag in ('구조검증상태','물성검증상태'):
            if x.get(tag)!='승인':raise ValueError(f"{x['CAS']}: {tag} 근거 미승인")
        for tag in ('SMILES','분자량_g_mol','25C_포화증기압_kPa','구조공식출처','물성출처와측정조건','실측또는DB근거문헌'):
            if not x.get(tag,'').strip():raise ValueError(f"{x['CAS']}: {tag} 누락")
        for tag in ('분자량_g_mol','25C_포화증기압_kPa'):
            if float(x[tag])<=0:raise ValueError(f"{x['CAS']}: 양의 물성 필요")
        if abs(float(x.get('온도_K') or '0')-298.15)>1e-3:raise ValueError('25C 외 물성 적용 금지')
    return [x for x in records if x.get('HANNA입력승인')=='승인']

def main(argv=None):
    parser=argparse.ArgumentParser()
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--check-approved-properties',type=Path)
    a=parser.parse_args(argv)
    if a.check_approved_properties:
        print('approved properties:',len(approved_property_records(a.check_approved_properties)))
    create_report(a.source,a.output)
if __name__=='__main__':main()